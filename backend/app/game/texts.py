def level_for_xp(xp: int) -> dict:
    cur = LEVELS[0]
    for lv in LEVELS:
        if xp >= lv["xp"]:
            cur = lv
    return cur

def next_level_xp(xp: int) -> int | None:
    for lv in LEVELS:
        if lv["xp"] > xp:
            return lv["xp"]
    return None
